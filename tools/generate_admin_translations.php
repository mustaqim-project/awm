foreach ($translations as $k => $trans) {
    $pattern = "/^(\s*[\x27\x22]" . preg_quote($k, '/') . "[\x27\x22]\s*=>\s*)[\x27\x22](?:[^\x5C\x27\x22]|\\\\.)*[\x27\x22](,\s*)$/m";
